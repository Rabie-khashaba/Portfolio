import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'src/data/projectKnowledge.generated.js');
const textExtensions = new Set(['.css', '.html', '.js', '.jsx', '.json', '.jsonc', '.md', '.txt']);
const excludedDirectories = new Set(['.git', '.next', '.wrangler', 'dist', 'node_modules']);
const excludedFiles = new Set(['package-lock.json', '.dev.vars']);

async function collect(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!excludedDirectories.has(entry.name) && !entry.name.startsWith('.')) {
        files.push(...(await collect(path.join(directory, entry.name))));
      }
      continue;
    }

    const absolutePath = path.join(directory, entry.name);
    if (absolutePath === output || excludedFiles.has(entry.name) || !textExtensions.has(path.extname(entry.name))) continue;
    if (/\.(env|secret|pem|key)$/i.test(entry.name)) continue;
    files.push(absolutePath);
  }

  return files;
}

const files = (await collect(root)).sort();
const sections = await Promise.all(files.map(async (file) => {
  const relativePath = path.relative(root, file).replaceAll(path.sep, '/');
  const contents = await readFile(file, 'utf8');
  return `### ${relativePath}\n${contents}`;
}));

await writeFile(output, `// Generated by scripts/generate-project-knowledge.js. Do not edit by hand.\nexport const projectKnowledge = ${JSON.stringify(sections.join('\n\n'))};\n`);
console.log(`Indexed ${files.length} text files (${sections.join('\n\n').length.toLocaleString()} characters).`);
